import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
const root = new URL("..", import.meta.url);
const source = await readFile(new URL("js/roadmap-orbit.js", root), "utf8");
const html = await readFile(new URL("roadmap.html", root), "utf8");
const css = await readFile(new URL("css/roadmap.css", root), "utf8");
assert.match(source, /const systems =/);
assert.doesNotMatch(source, /state:\s*"planned"[^\n]+GPU particles/);
assert.match(source, /ParticleGpuRuntime\.cpp/);
assert.match(source, /PhysicsWorld\.h/);
assert.match(source, /setAttribute\("tabindex", "0"\)/);
assert.match(source, /pointerenter/);
assert.match(source, /event\.key === "Enter"/);
assert.match(source, /node\.source/);
assert.match(html, /roadmap-orbit-legend/);
assert.match(html, /data-i18n="roadmap\.orbit\.legend\.shipped"/);
assert.match(css, /transform-origin:center/);
assert.match(css, /prefers-reduced-motion:\s*reduce/);
assert.match(css, /max-width:\s*560px/);
console.log("Roadmap orbit evidence, input, legend, mobile and motion contracts passed.");
